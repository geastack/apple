#!/usr/bin/env node
// Writes the TU that tells the engine's runtime TTF slots which glyphs beyond
// printable ASCII to cover (generated::runtimeTtfDeclaredCodepoints).
//
// The font generator puts that set -- its raster baseline plus every
// `--gea-font-charset` the app's CSS names -- into gea_embedded_font_generated.cpp,
// but a windowed macOS build does not link that TU (it carries baked atlases the
// window never uses), and resident builds prefix its symbols. Without this file
// the engine's weak default applies and `·`, `€`, `–` render as `?`.
//
// usage: runtime-glyphs.mjs --out <file.cpp> <gea_embedded_font_generated.cpp>...
import fs from 'node:fs'

const args = process.argv.slice(2)
const outIndex = args.indexOf('--out')
if (outIndex < 0 || !args[outIndex + 1]) {
  console.error('usage: runtime-glyphs.mjs --out <file.cpp> <font-generated.cpp>...')
  process.exit(2)
}
const out = args[outIndex + 1]
const inputs = args.filter((_, i) => i !== outIndex && i !== outIndex + 1)

const codepoints = new Set()
for (const input of inputs) {
  if (!fs.existsSync(input)) continue
  const match = fs.readFileSync(input, 'utf8').match(/kRuntimeTtfDeclaredCodepoints\[\]\s*=\s*\{([^}]*)\}/)
  if (!match) continue
  for (const token of match[1].split(',')) {
    const value = Number(token.trim())
    if (Number.isInteger(value) && value > 0x7e) codepoints.add(value)
  }
}
const list = [...codepoints].sort((a, b) => a - b)
const source = [
  '// Generated by @geastack/apple targets/macos/runtime-glyphs.mjs. Do not edit.',
  'namespace gea::framework::graphics::generated {',
  '',
  `static const int kDeclared[] = {${list.length > 0 ? list.map((cp) => `0x${cp.toString(16)}`).join(', ') : '0'}};`,
  '',
  'const int *runtimeTtfDeclaredCodepoints(int *count)',
  '{',
  `    if (count) *count = ${list.length};`,
  '    return kDeclared;',
  '}',
  '',
  '}  // namespace gea::framework::graphics::generated',
  '',
].join('\n')
if (!fs.existsSync(out) || fs.readFileSync(out, 'utf8') !== source) fs.writeFileSync(out, source)
